def наблюдатели(agent: MemoryAgent, трейс: bool):
    """Пара обработчиков, печатающих ход сценария по мере дела.

    Пять шагов идут от полутора минут и дольше. Печатать всё в конце — значит
    заставить человека смотреть в неподвижный экран; поэтому ответ каждого шага
    выводится сразу, как только он получен.
    """

    def перед(шаг, номер, всего):
        print(f"\n[{номер}/{всего}] {шаг.агент} — {шаг.стадия}, "
              f"{agent.runner.model_for(шаг)}…", flush=True)

    def после(результат, номер, всего):
        личный = " (ответ вам)" if номер == всего else " (вход следующего шага)"
        print("-" * 78)
        текст = результат.текст.strip()
        if not трейс and номер != всего and len(текст) > 600:
            текст = текст[:600] + "…"
        print(текст)
        print(f"[{tokens.format_tokens(результат.токенов)} токенов{личный}]", flush=True)

    return перед, после


