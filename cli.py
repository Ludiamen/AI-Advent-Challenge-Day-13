def показать_память(agent: MemoryAgent) -> int:
    сводка = agent.stats()
    print(LINE)
    print("СЛОИ ПАМЯТИ")
    print(LINE)
    коротко = сводка[SHORT]
    print(f"  краткосрочная   реплик {коротко['реплик']}, символов {коротко['символов']}"
          f"  (сессия «{agent.session}»)")
    рабочая = сводка[WORKING]
    print(f"  рабочая         задач в работе: {рабочая['задач']}")
    for задача in agent.tasks():
        print(f"      {задача['task_id']:<24} {задача['stage_label']:<12} "
              f"план {задача['plan_steps']}, собрано {задача['collected']}")
    долго = сводка[LONG]
    print(f"  долговременная  профиль: {долго['сводка']}"
          + ("" if долго["настроен"] else "  (мастер настройки не проходили)"))
    print(f"                  записей {долго['профиль']}, инвариантов {долго['инвариантов']}, "
          f"сценариев {долго['сценариев']}, решений {долго['решений']}, "
          f"знаний {долго['знаний']}")
    print(LINE)
    print("Включены сейчас:", ", ".join(sorted(agent.layers)) or "ни одного")
    return 0


def показать_профиль(agent: MemoryAgent) -> int:
    профиль = agent.profile()
    print(LINE)
    print(f"ПРОФИЛЬ «{agent.user_id}» — {preferences.summary(профиль)}")
    print(LINE)
    if agent.needs_setup():
        print("Профиль ещё не настраивали. Мастер: python cli.py --настроить")
        print()
    for раздел in preferences.SECTIONS:
        print(f"{раздел.capitalize()} (настраивает пользователь):")
        for поле in preferences.fields(раздел):
            значение = профиль[раздел][поле.key]
            если_проверяется = ""
            if поле.check:
                если_проверяется = "  ← проверяется кодом" if поле.hard else "  ← мягкая проверка"
            показ = {True: "да", False: "нет"}.get(значение, значение) or "—"
            print(f"  {раздел}/{поле.key:<12} {str(показ):<22}{если_проверяется}")
        print()
    if профиль.get("контекст"):
        print("Зачем:", профиль["контекст"])
        print()
    записи = профиль.get("ограничения") or {}
    if записи:
        print("Ограничения проекта:")
        for ключ, значение in записи.items():
            print(f"  {ключ:<14} {значение}")
        print()
    правила = профиль.get("инварианты") or []
    print(f"Инварианты ({len(правила)}):")
    for правило in правила:
        как = правило.get("тип")
        проверка = "кодом" if как != "мягкий" else "моделью (замечание, не запрет)"
        print(f"  [{правило.get('код')}] {правило.get('правило')}")
        print(f"      проверяется {проверка}"
              + (f"; ищем: {', '.join(правило.get('значения', []))}" if правило.get("значения") else ""))
    return 0


def показать_заготовки() -> int:
    print(LINE)
    print("ГОТОВЫЕ ПРОФИЛИ")
    print(LINE)
    for з in interview.describe_templates():
        print(f"  {з['имя']:<10} {з['описание']}")
        print(f"  {'':<10} {з['сводка']}")
    print(LINE)
    print("Взять: python cli.py --кто тимлид --заготовка тимлид")
    return 0


def показать_сценарии(agent: MemoryAgent) -> int:
    сценарии = agent.scenarios()
    print(LINE)
    print(f"СЦЕНАРИИ ПОЛЬЗОВАТЕЛЯ «{agent.user_id}» — {len(сценарии)}")
    print(LINE)
    for сценарий in сценарии:
        print(f"{сценарий.имя} — {сценарий.описание}")
        print(f"  запускается по: {', '.join(сценарий.триггеры) or 'только явно'}")
        for номер, шаг in enumerate(сценарий.шаги, 1):
            вход = ", ".join(шаг.вход)
            print(f"  {номер}. {шаг.агент:<14} {шаг.стадия:<11} {шаг.model_key:<14} вход: {вход}")
            print(f"     {шаг.задача[:100]}")
        print()
