def спросить(agent: MemoryAgent, вопрос: str, трейс: bool, сценарии: bool,
             по_шагам: bool = False) -> None:
    """Один вопрос: либо сценарием, если сработал триггер, либо обычным ответом."""
    сценарий = agent.match_scenario(вопрос) if сценарии else None
    if сценарий is not None:
        print(f"Сработал сценарий «{сценарий.имя}»: "
              f"{' → '.join(ш.агент for ш in сценарий.шаги)}")

        перед, после = наблюдатели(agent, трейс)
        итог = agent.run_scenario(вопрос, name=сценарий.имя, on_step=перед,
                                  on_result=после, по_шагам=по_шагам)
        показать_прогон(итог, трейс)
        return

    ответ = agent.ask(вопрос)
    print(f"\n{ответ.text}")
    if ответ.blocked:
        print("\n! Ответ нарушает инварианты и не был исправлен за отведённые попытки.")
    if трейс:
        показать_трейс(ответ)
    показать_расход(ответ)


