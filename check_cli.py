def прогнать_сценарий(модель: str, отчёт: list[Итог]) -> str:
    """Части 3-4: продолжение отложенной задачи в новых процессах."""
    задачи = запустить(Шаг("3.2б", "Найти задачу сценария", ["--задачи"]), модель)
    совпадение = re.search(r"(напиши-фичу-[\w-]+)", задачи.вывод)
    if not совпадение:
        return ""
    task_id = совпадение.group(1)

    заходов = 0
    while заходов < 6:
        заходов += 1
        данные = состояние_задачи(task_id)
        if not данные["пауза"]:
            break
        ждёт_ответа = данные["ожидание"] == "ответ-пользователя"
        ключи = ["--по-шагам", "--задача", task_id]
        ключи += (["--ответ", "Колодцы лежат в gisdata отдельным слоем, SRID 3857."]
                  if ждёт_ответа else ["--продолжить"])
        шаг = Шаг(f"4.{заходов}",
                  "Продолжение в новом процессе"
                  + (" (с ответом на вопрос шага)" if ждёт_ответа else ""),
                  ключи,
                  [("прогон пошёл дальше", по_выражению(r"\d/5|Сценарий отработал|решение")),
                   ("пройденное не переигрывается",
                    lambda текст, н=данные["текущий_шаг"]: f"{н}/5" in текст
                    or "отработал" in текст.lower())])
        итог = запустить(шаг, модель)
        отчёт.append(итог)
        print(f"  {итог.шаг.номер} {итог.шаг.название}: "
              + ("ок" if итог.удача else "РАСХОЖДЕНИЕ"))
        if not os.path.exists(os.path.join(ПАМЯТЬ, "working", f"{task_id}.json")):
            break                                   # задача свёрнута в решение
    return task_id


# --- отчёт --------------------------------------------------------------------

def отчёт_в_markdown(итоги: list[Итог], модель: str, task_id: str,
                     секунд: float) -> str:
    всего = sum(len(и.сошлось) for и in итоги)
    сошлось = sum(1 for и in итоги for _, ок in и.сошлось if ок)
    строки = [
        "# Результат консольной проверки Дня 13",
        "",
        f"Прогон: `python check_cli.py`, модель **{модель or 'по роли'}**, "
        f"память в `cli-check-memory/`.",
        f"Дата: {time.strftime('%Y-%m-%d %H:%M')}. Заняло {секунд / 60:.1f} мин.",
        "",
        f"**Ожиданий проверено: {всего}, сошлось: {сошлось}, "
        f"расхождений: {всего - сошлось}.**",
        "",
        "Каждая строка — отдельный запуск `cli.py` своим процессом. Это и есть",
        "доказательство дня: состояние задачи живёт на диске, поэтому",
        "продолжение работает в процессе, который о прошлом не знает ничего.",
        "",
        "## Сводка",
        "",
        "| шаг | проверка | команда | итог | секунд |",
        "|---|---|---|---|---|",
    ]
    for и in итоги:
        # В таблице оставляем только то, чем шаги отличаются: общие ключи
        # (каталог памяти и модель) вынесены в шапку отчёта.
        ключи = (и.команда.replace("cli.py ", "")
                 .replace(f"--память-в {ПАМЯТЬ_ОТН} ", "")
                 .replace(f"--модель {модель} ", "").strip())
        строки.append(f"| {и.шаг.номер} | {и.шаг.название} | `{ключи or '(диалог)'}` | "
                      f"{'ок' if и.удача else '**расхождение**'} | {и.секунд:.1f} |")
    строки += ["", "## Подробности", ""]
    for и in итоги:
        строки.append(f"### {и.шаг.номер}. {и.шаг.название}")
        строки.append("")
        строки.append(f"```\n$ python {и.команда}\n```")
        строки.append("")
        for описание, ок in и.сошлось:
            строки.append(f"- {'✓' if ок else '✗'} {описание}")
        if и.заметка:
            строки.append(f"- ℹ {и.заметка}")
        строки.append("")
        кусок = "\n".join(и.вывод.strip().splitlines()[:14])
        if кусок:
            # Ограждение из четырёх кавычек, а не трёх: в выводе шагов сценария
            # попадается код в обычных тройных кавычках, и он рвал разметку
            # отчёта пополам — дальше markdown читался как продолжение кода.
            строки.append("<details><summary>вывод</summary>")
            строки.append("")
            строки.append("````")
            строки.append(кусок)
            строки.append("````")
            строки.append("")
            строки.append("</details>")
            строки.append("")
    if task_id:
        строки += ["## Состояние задачи сценария на диске", ""]
        путь = os.path.join(ПАМЯТЬ, "working", f"{task_id}.json")
        if os.path.exists(путь):
            данные = состояние_задачи(task_id)
            строки.append("```json")
            строки.append(json.dumps({
                "task_id": данные["task_id"], "stage": данные["stage"],
                "текущий_шаг": данные["текущий_шаг"], "ожидание": данные["ожидание"],
                "пауза": данные["пауза"], "причина_паузы": данные["причина_паузы"],
                "шаги": [{"номер": ш["номер"], "имя": ш["имя"],
                          "состояние": ш["состояние"]} for ш in данные["шаги"]],
            }, ensure_ascii=False, indent=2))
            строки.append("```")
        else:
            строки.append(f"Задача `{task_id}` доведена до конца и свёрнута в "
                          "журнал решений — в рабочей памяти её больше нет.")
        строки.append("")

    строки += [
        "## Что это доказывает",
        "",
        "| Требование дня | Шаги прогона |",
        "|---|---|",
        "| этап / шаг / ожидаемое действие | 1.2, 1.4б |",
        "| задача не перепрыгивает этап | 1.3, 1.5 |",
        "| пауза на любом этапе | 2.1, 2.2, 3.1 |",
        "| продолжение без повторных объяснений | 4.x |",
        "| состояние живёт вне процесса | 2.2, 3.2, 4.x |",
        "| состояние читается глазами | 5.1 и файл задачи выше |",
        "",
        "Каждый шаг — отдельный процесс `cli.py`. Между 3.1 и 4.x процесс,",
        "запустивший сценарий, уже завершился: продолжение поднимает задачу",
        "с диска и доделывает ровно оставшиеся шаги.",
        "",
    ]
    return "\n".join(строки)


def main() -> int:
    разбор = argparse.ArgumentParser(
        description="Прогон консольного чек-листа Дня 13 с отчётом в markdown.")
    разбор.add_argument("--модель", dest="model", default="ds-flash",
                        help="модель для живых вызовов (по умолчанию ds-flash)")
    разбор.add_argument("--в", dest="report", default="CLI-CHECK-RESULTS.md",
                        help="файл отчёта (по умолчанию CLI-CHECK-RESULTS.md)")
    разбор.add_argument("--без-сценария", dest="no_scenario", action="store_true",
                        help="пропустить пятишаговый прогон сценария")
    аргументы = разбор.parse_args()

    shutil.rmtree(ПАМЯТЬ, ignore_errors=True)
    начало = time.time()
    итоги: list[Итог] = []
    task_id = ""

    print(f"{LINE}\nКОНСОЛЬНАЯ ПРОВЕРКА ДНЯ 13, модель {аргументы.model}\n{LINE}")
    for шаг in шаги(not аргументы.no_scenario):
        итог = запустить(шаг, аргументы.model)
        итоги.append(итог)
        метка = "ок" if итог.удача else "РАСХОЖДЕНИЕ"
        print(f"  {шаг.номер} {шаг.название}: {метка} ({итог.секунд:.1f} с)")
        for описание, ок in итог.сошлось:
            if not ок:
                print(f"      ✗ {описание}")
        if шаг.номер == "3.2" and not аргументы.no_scenario:
            task_id = прогнать_сценарий(аргументы.model, итоги)

    текст = отчёт_в_markdown(итоги, аргументы.model, task_id, time.time() - начало)
    with open(os.path.join(КОРЕНЬ, аргументы.report), "w", encoding="utf-8") as файл:
        файл.write(текст)

    расхождений = sum(1 for и in итоги for _, ок in и.сошлось if not ок)
    print(LINE)
    print(f"Отчёт записан в {аргументы.report}. Расхождений: {расхождений}.")
